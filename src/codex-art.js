// '.'는 비워 두고 나머지 글자만 덮는다.
function put(g, spr, x, y) {
  spr.forEach((row, j) => [...row].forEach((c, i) => {
    if (c !== '.' && g[y + j] && x + i >= 0 && x + i < 16) g[y + j][x + i] = c;
  }));
}

function fig({ hair = 'b', robe = 'b', shade, beard, beardColor, long, skin = 's', eye = 'o', hold = [] }) {
  const g = BODY.map((r) => [...r]);
  if (long) put(g, LONG, 0, 2);
  if (beard) put(g, beard === 'long' ? BEARD_LONG : BEARD_SHORT, 0, 5);
  const robeAt = (y) => robe[y % robe.length];
  const map = (c, y) => ({ H: hair, S: skin, E: eye, B: beardColor ?? hair, R: robeAt(y), A: shade ?? SHADE[robe[0]] }[c] ?? c);
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) g[y][x] = map(g[y][x], y);
  for (const [spr, x, y] of hold) put(g, spr, x, y);
  return g.map((r) => r.join(''));
}

